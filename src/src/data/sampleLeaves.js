/**
 * Helper to fetch a sample image as a native JS File object.
 * Enables seamless integration with existing file upload pipelines.
 */
export async function loadSampleAsFile(sample) {
  const response = await fetch(sample.imageUrl);
  if (!response.ok) {
    throw new Error(`Failed to load sample image: ${response.statusText}`);
  }
  const blob = await response.blob();
  const file = new File([blob], sample.fileName, { type: blob.type || 'image/jpeg' });
  // Attach metadata for intelligent demo analyzer
  file.sampleMeta = sample;
  return file;
}
